function startMode(m) {
  if (selectedChapter === null) return;

  mode        = m;
  activeWords = selectedChapter === 0
    ? WORDS
    : WORDS.filter(w => w.chapter === selectedChapter);

  queue     = shuffle(activeWords).map(w => ({ word: { ...w }, isRetry: false }));
  totalOrig = queue.length;
  mastered  = new Set();
  answered  = 0;

  showScreen('quizScreen');

  const chLabel = CHAPTER_INFO[selectedChapter].label;
  $('chapterLabel').textContent = chLabel;
  $('hintEl').textContent = m === 1
    ? '한글 뜻을 고르세요'
    : '같은 분류의 영어 단어를 고르세요';

  nextQ();
}

// ================================================================
//  다음 문제
// ================================================================
function nextQ() {
  if (mastered.size >= totalOrig || queue.length === 0) {
    showDone();
    return;
  }

  const item = queue[0];
  curWord = item.word;

  $('retryBadge').classList.toggle('hidden', !item.isRetry);
  updateProgress();

  if (mode === 1) {
    renderMode1();
  } else {
    renderMode2();
  }
}

// ================================================================
//  모드 1: 영어 → 한글 뜻
// ================================================================
function renderMode1() {
  $('wordEl').textContent = curWord.en;

  const wrong3 = shuffle(activeWords.filter(w => w.id !== curWord.id))
    .slice(0, 3)
    .map(w => w.ko);

  const opts = shuffle([curWord.ko, ...wrong3]);

  curCorrectKey = curWord.ko;
  curCorrectAns = { text: curWord.ko };

  buildChoices(opts, chosen => {
    const ok = chosen === curWord.ko;
    advance(ok);
    openPopup(ok, chosen);
  });
}

// ================================================================
//  모드 2: 같은 카테고리 영어 단어 찾기
// ================================================================
function pickDistinctWrongOptions(pool, excludeText, n) {
  const seen = new Set([excludeText]);
  const result = [];
  for (const w of shuffle(pool)) {
    if (seen.has(w.en)) continue;
    seen.add(w.en);
    result.push(w.en);
    if (result.length === n) break;
  }
  return result;
}

function renderMode2() {
  $('wordEl').textContent = curWord.en;

  const chapterPool = WORDS.filter(w => w.chapter === curWord.chapter);
  const same = chapterPool.filter(w => w.cat === curWord.cat && w.id !== curWord.id);

  if (!same.length) {
    mastered.add(queue.shift().word.id);
    nextQ();
    return;
  }

  const correctW = shuffle(same)[0];

  const wrong3 = pickDistinctWrongOptions(
    chapterPool.filter(w => w.cat !== curWord.cat),
    correctW.en,
    3
  );

  if (wrong3.length < 3) {
    const seen = new Set([correctW.en, ...wrong3]);
    for (const w of shuffle(WORDS.filter(w => w.cat !== curWord.cat))) {
      if (wrong3.length >= 3) break;
      if (seen.has(w.en)) continue;
      seen.add(w.en);
      wrong3.push(w.en);
    }
  }

  const opts = shuffle([correctW.en, ...wrong3]);

  curCorrectKey = correctW.en;
  curCorrectAns = { text: correctW.en, sub: correctW.ko };

  buildChoices(opts, chosen => {
    const ok = chosen === correctW.en;
    advance(ok);
    openPopup(ok, chosen);
  });
}

// ================================================================
//  선택지 렌더링
// ================================================================
function buildChoices(opts, handler) {
  const container = $('choicesEl');
  container.innerHTML = '';

  opts.forEach(opt => {
    const btn = document.createElement('button');
    btn.className   = 'choice-btn';
    btn.textContent = opt;
    btn.onclick = () => {
      container.querySelectorAll('button').forEach(b => (b.disabled = true));
      handler(opt);
    };
    container.appendChild(btn);
  });
}

// ================================================================
//  정답 처리
// ================================================================
function advance(isCorrect) {
  const item = queue.shift();
  answered++;

  if (isCorrect) {
    mastered.add(item.word.id);
  } else {
    const pos = Math.min(RETRY_AFTER, queue.length);
    queue.splice(pos, 0, { word: { ...item.word }, isRetry: true });
  }
}

// ================================================================
//  팝업
// ================================================================
function openPopup(isCorrect, userChose) {
  $('sheetHead').className = 'sheet-head ' + (isCorrect ? 'correct' : 'incorrect');
  $('sheetEmoji').textContent = isCorrect ? '😀' : '😕';
  $('sheetTitle').textContent = isCorrect ? 'Correct' : 'Study this one!';

  $('sheetWord').textContent = curWord.en;

  if (isCorrect) {
    $('sheetCorrectLbl').textContent = mode === 1 ? 'Goes with:' : 'Same category as:';
    $('sheetWrong').classList.add('hidden');
  } else {
    $('sheetCorrectLbl').textContent = 'Correct answer:';
    $('sheetWrong').classList.remove('hidden');
    $('sheetUserAns').textContent = userChose;
  }

  $('sheetCorrectAns').textContent = curCorrectAns.text;

  if (curCorrectAns.sub) {
    $('sheetCorrectSub').textContent = '(' + curCorrectAns.sub + ')';
    $('sheetCorrectSub').classList.remove('hidden');
  } else {
    $('sheetCorrectSub').classList.add('hidden');
  }

  $('overlay').classList.remove('hidden');
}

// ================================================================
//  Continue
// ================================================================
function continueQuiz() {
  $('overlay').classList.add('hidden');
  nextQ();
}

// ================================================================
//  진행도
// ================================================================
function updateProgress() {
  const m       = mastered.size;
  const display = Math.min(m + 1, totalOrig);

  $('progressText').textContent = `${display} / ${totalOrig}`;
  $('progFill').style.width     = ((m / totalOrig) * 100) + '%';
}

// ================================================================
//  완료 화면
// ================================================================
function showDone() {
  showScreen('doneScreen');

  const accuracy = answered > 0
    ? Math.round((mastered.size / answered) * 100)
    : 100;

  const chLabel = CHAPTER_INFO[selectedChapter].label;

  $('doneStats').innerHTML =
    `<strong>${chLabel}</strong> · 전체 <strong>${totalOrig}개</strong> 단어 완료! 🎊<br>` +
    `총 시도: ${answered}번 &nbsp;|&nbsp; 정확도: ${accuracy}%`;
}
